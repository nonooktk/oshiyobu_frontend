//      画面の段階の名前（ゲージ）と、称賛の演出の文字・褒めことば（praise.ts）は、統括が決めた名前なので、ここでは変えない。
import type { ArtistId } from '../../core';
import type { HeatStage } from '../domain/heat';

/** ホームのコメントのキー（SP-30）。 */
export type HomeKey = 'reached' | 'gathered' | 'pre' | 'preSoon' | 'post' | 'postSoon' | 'friend';
/** 行動ごとのひとこと（特典の絵の下・やめるのトースト・称賛の演出の下の枠）。 */
export type SayKey = 'join' | 'share' | 'friend' | 'quit' | 'gift';

export type Voice = {
  /** 話す人の名前。Tech0 だけ、メンバーのカマヤーンが代表して話す（吹き出しの上に添える）。 */
  who?: string;
  /**
   * (熱量の段階 1〜5, 市の名前) → 折り返してよい区切りごとの配列。1 つのセリフは、幅 320〜390px の吹き出しで 3 行以内。
   * 人数・割合・金額の数字は言わない（G-08）。距離は、段階に合わせた言い回しで伝える。
   * 場面: pre ＝ 申し込む前（推し活定期をはじめる前・預金を積み増す前も含む。申し込めるとは言わない）／
   * post ＝ 申し込んだあと／friend ＝ 仲間を呼んだあと／gathered ＝ 人数は集まったが開催は未定／reached ＝ 開催が決まった。
   * preSoon・postSoon は、熱量が高い（段階 4 以上）とき。
   */
  home: Record<HomeKey, (stage: HeatStage, city: string) => string[]>;
  say: {
    join: (city: string) => string;
    share: () => string;
    friend: () => string;
    quit: () => string;
    /** t は「特典 1/3」の形。 */
    gift: (t: string) => string;
  };
};

